// Regenerates src/utils/inventoryImport.js (browser global) from the shop-admin parser so both portals
// read supplier Excel/JSON files the same way. Run after editing the shop-admin file:
//   node scripts/sync-inventory-import.js
const fs = require('fs');
const path = require('path');

const SOURCE = path.resolve(__dirname, '../../infinest-frontend/src/components/shop-admin/sales/inventoryImport.js');
const TARGET = path.resolve(__dirname, '../src/utils/inventoryImport.js');

const src = fs.readFileSync(SOURCE, 'utf8');
const names = [...src.matchAll(/^export (?:async )?function (\w+)/gm)].map((m) => m[1]);
const body = src
  .replace('import * as XLSX from "xlsx";', 'var XLSX = window.XLSX;')
  .replace(/^export (async )?function /gm, '$1function ');
if (/^\s*(import|export)\b/m.test(body)) throw new Error('Unconverted import/export in ' + SOURCE);

const out = `// GENERATED by scripts/sync-inventory-import.js from
// infinest-frontend/src/components/shop-admin/sales/inventoryImport.js — edit that file, then re-run the script.
// Needs the SheetJS global (window.XLSX) loaded before this script.
(function () {
${body.trim()}

window.InventoryImport = { ${names.join(', ')} };
})();
`;
fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, out);
console.log(`Wrote ${path.relative(process.cwd(), TARGET)} (${names.length} functions: ${names.join(', ')})`);
